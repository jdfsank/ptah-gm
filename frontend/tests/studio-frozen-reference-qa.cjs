/* Frozen input visibility from the fourth trial; fixtures are not acceptance. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const dom = new JSDOM(fs.readFileSync(path.join(root, 'studio/index.html'), 'utf8'), { url: 'http://127.0.0.1:8123/studio/', pretendToBeVisual: true });
delete global.document; delete global.window; global.Option = dom.window.Option;
global.location = dom.window.location; global.history = dom.window.history; global.localStorage = dom.window.localStorage;
const tick = () => new Promise(resolve => setTimeout(resolve, 0));

(async () => {
  const { StudioApp } = await import(pathToFileURL(path.join(root, 'studio/studio.js')).href);
  global.document = dom.window.document; global.window = dom.window;
  const projectId = 'frozen-project';
  const asset = { id: 'frozen-image', name: 'concept.png', width: 1774, height: 887, size: 1923754, generation: { model: 'gpt-image-2', requestedSize: '1536x1024' } };
  const intent = { assetId: asset.id, intent: '  仅采纳黄色雨衣\n与右侧暖光。', preserve: '保留程序图形', unknown: '纹理不约束', targetObjectIds: [] };
  const proposal = { id: 'frozen-proposal', projectId, workflow: 'objects-v1', status: 'FROZEN', revision: 2, publicationRevision: 1, baseCommit: 'git-base', packetId: 'frozen-packet', reviewedPlanRef: 'frozen-plan', text: '新的概念文本不属于冻结轮', assets: [], visualReferences: [] };
  const packet = { id: proposal.packetId, packetId: proposal.packetId, projectId, proposalId: proposal.id, proposalRevision: 2, publicationRevision: 1, baseCommit: 'git-base', reviewedPlanRef: proposal.reviewedPlanRef, userText: '冻结时的用户原文', assets: [asset], visualReferences: [intent] };
  const result = { projectId, reviewedPlanRef: proposal.reviewedPlanRef, plan: { ...proposal, document: { objects: [], requirements: [] }, tasks: [] } };
  const app = new StudioApp({ documentImpl: document, fetchImpl: async () => { throw new Error('unexpected request'); } });
  app.projectId = projectId; app.workflow = 'objects-v1'; app.protocolVersion = 1;
  app.handshake = { storeId: 'frozen-store' }; app.manager = { projects: [{ id: projectId, protocolVersion: 1, workflow: 'objects-v1' }] };
  app.workspace = { proposals: [proposal], packets: [packet], jobs: [] };
  app.proposal = proposal; app.packet = packet; app.reviewedPlan = result; app.readiness = { ready: true };
  app.assets = [{ ...asset, id: 'later-image' }]; app.referenceIntents = { 'later-image': { intent: '后来用途' } };
  for (const id of ['workspace', 'project-view']) document.getElementById(id).classList.remove('hidden');
  const draftBefore = JSON.stringify(app.proposalInputs);
  const packetBefore = JSON.stringify(packet);
  app.renderPacketPreview({ ...proposal, status: 'READY' });
  app.renderProposal(); app.renderFrozenPacket();
  let section = document.querySelector('#reviewed-plan-content');
  assert(section && !section.open, 'frozen plan starts collapsed');
  section.querySelector('summary').click(); await tick();
  assert(section.open, 'normal summary activation opens the frozen plan');
  assert(document.querySelector('#freeze-area').classList.contains('hidden'), 'dispatch controls remain hidden');
  const visibleInput = () => document.querySelector('#reviewed-plan-content .frozen-plan-input');
  let input = visibleInput();
  assert(input, 'the open frozen plan contains its own frozen input');
  assert(!input.closest('.hidden,[hidden]'), `frozen input has no hidden ancestor: ${input.closest('.hidden,[hidden]')?.id}`);
  assert.equal(input.querySelector('img').getAttribute('src'), `/api/projects/${projectId}/assets/${asset.id}`);
  assert([...input.querySelectorAll('.visual-raw')].some(node => node.textContent === intent.intent), 'adoption text remains verbatim');
  assert(input.textContent.includes(packet.userText) && !input.textContent.includes(proposal.text) && !input.textContent.includes('后来用途'), 'only frozen input supplies the image and original text');
  assert(input.textContent.includes(intent.preserve) && input.textContent.includes(intent.unknown));
  assert(input.textContent.includes('1774 × 887') && input.textContent.includes('1536x1024'));
  input.querySelector('img').dispatchEvent(new dom.window.Event('error')); await tick();
  assert(input.textContent.includes('图片无法读取') && input.textContent.includes(intent.intent), 'unreadable images preserve the binding and adoption text');
  app.renderProposal(); await tick();
  section = document.querySelector('#reviewed-plan-content');
  assert(section.open && visibleInput().querySelector('img'), 'read-only refresh preserves the expanded frozen plan');
  const variants = [null, { ...packet, projectId: 'other-project' }, { ...packet, proposalId: 'other-proposal' }, { ...packet, proposalRevision: 1 }, { ...packet, id: 'other-packet', packetId: 'other-packet' }, { ...packet, id: 'other-packet' }, { ...packet, packetId: 'other-packet' }, { ...packet, reviewedPlanRef: 'other-plan' }, { ...packet, publicationRevision: 0 }, { ...packet, baseCommit: 'other-base' }];
  for (const variant of variants) {
    app.packet = variant; app.renderReviewedPlan(result);
    input = visibleInput();
    assert(input && !input.querySelector('img'), 'missing or conflicting frozen identity never borrows a reference');
    assert(input.textContent.includes('无法核对本计划绑定的冻结输入'));
    assert(!input.textContent.includes(intent.intent) && !input.textContent.includes('后来用途'));
  }
  app.packet = packet; app.proposal = { ...proposal, status: 'READY' }; app.renderReviewedPlan(result);
  assert(!visibleInput(), 'READY plans do not show a stale frozen packet');
  app.proposal = proposal; app.packet = { ...packet, assets: [], visualReferences: [] }; app.renderReviewedPlan(result);
  assert(!visibleInput().querySelector('img') && !visibleInput().textContent.includes(intent.intent), 'an input without references stays empty');
  assert.equal(JSON.stringify(app.proposalInputs), draftBefore, 'read-only inspection does not create a draft');
  assert.equal(JSON.stringify(packet), packetBefore, 'inspection never changes the frozen packet');
  assert.equal(document.querySelector('#reviewed').checked, false);
  assert.equal(document.querySelector('#freeze').disabled, true);
  app.destroy(); dom.window.close();
  console.log('PASS Studio frozen references: visible plan input, verbatim intent, strict identity, image failure, read-only refresh and no dispatch');
})().catch(error => { console.error(error.stack || error); dom.window.close(); process.exitCode = 1; });
