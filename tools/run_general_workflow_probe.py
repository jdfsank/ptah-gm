"""Actual native planning/production/Godot/API proof in isolated test storage.

Synthetic decisions prove protocol publication only; no production approval or
human gameplay acceptance is created. No standalone checksum is used.
"""
from __future__ import annotations

import argparse
import json
import sys
import threading
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.coordinator import Coordinator, canonical, now
from backend.server import make_server

CONCEPTS = [
    "Make a small 2D side-view jump game called Bridge Runner. Keyboard left/right and space jump; "
    "cross three visible platforms to a green exit, falling restarts, R resets, HUD explains controls and win. "
    "Use simple procedural shapes, no external assets/plugins/network. Fixed 960x540 camera, single level, "
    "no sound. Represent the player as object id player with editable numeric speed (220, min 50, max 500) "
    "and jump-speed (420, min 200, max 700). Represent the main scene as main-scene bound to scenes/main.tscn. "
    "Make each mechanism/object explicit with stable IDs and source bindings. This fully specified "
    "isolated test authorizes the MVP plan; do not ask optional questions, use READY unless a real blocker exists.",
    "Make a small 2D mouse-driven Lights Out puzzle called Light Grid. A 3x3 grid of buttons, "
    "clicking one toggles it and orthogonal neighbors. Win when all lights are off; show move count and "
    "a win message; R reset and a Reset button. Fixed solvable start generated by a known sequence of "
    "toggles from the solved board. Procedural colored squares and labels, no external assets/plugins/"
    "network/audio. Fixed 960x540 window. Object ids main-scene (scenes/main.tscn), puzzle-board, rules, hud. "
    "Expose an editable choice accent color on puzzle-board. Explicit source bindings and manual gameplay "
    "requirements. The fully specified isolated test authorizes the MVP plan; use READY unless blocked."
]


def run(state_root: Path, output: Path):
    if state_root == (ROOT / ".workbench").resolve() or state_root.exists():
        raise ValueError("use a fresh isolated state root, never production .workbench")
    coordinator = Coordinator(ROOT, state_root=state_root, test_data=True)
    server = make_server(coordinator, port=0)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    origin = f"http://127.0.0.1:{server.server_port}"
    token = None
    record = {"schemaVersion": 1, "status": "FAIL", "testData": True,
              "productionAuthorized": False, "humanAcceptance": "NOT PERFORMED",
              "startedAt": now(), "stateRoot": str(state_root), "events": [], "rounds": []}

    def save():
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(json.dumps(record, ensure_ascii=False, indent=2, allow_nan=False) + "\n")

    def request(path, body=None):
        headers = {"Accept": "application/json", "Origin": origin}
        if body is not None:
            headers.update({"Content-Type": "application/json", "X-Workbench-Token": token})
        req = urllib.request.Request(origin + "/api" + path,
            data=canonical(body).encode() if body is not None else None, headers=headers)
        with urllib.request.urlopen(req, timeout=45) as response:
            value = json.load(response)
        record["events"].append({"at": now(), "path": path, "method": "POST" if body is not None else "GET",
            "id": value.get("id"), "status": value.get("status")})
        return value

    def wait(path, active, timeout):
        end, previous = time.monotonic() + timeout, None
        while time.monotonic() < end:
            value = request(path)
            if value["status"] != previous:
                print(value["status"], value.get("summary", value.get("message", ""))[:220], flush=True)
                previous = value["status"]
            if value["status"] not in active:
                return value
            time.sleep(1)
        raise TimeoutError("probe wait exceeded: " + path)

    def produce(body, label):
        concept = request("/concepts", {"workflow": "objects-v1", **body})
        round_record = {"label": label, "proposalId": concept["id"], "projectId": concept["projectId"]}
        record["rounds"].append(round_record)
        save()
        proposal = wait("/proposals/" + concept["id"], {"PLANNING", "PLANNING_CANCELLING"}, 450)
        round_record["proposal"] = proposal
        save()
        if proposal["status"] != "READY":
            raise AssertionError("native planner did not yield READY: " + proposal["summary"])
        packet = request("/proposals/" + proposal["id"] + "/freeze", {
            "expectedRevision": proposal["revision"],
            "expectedPublicationRevision": proposal["publicationRevision"], "reviewedProposal": proposal})
        round_record["packet"] = packet
        dispatch = {"packetId": packet["id"], "idempotencyKey": "probe:" + packet["id"]}
        job = request("/jobs", dispatch)
        assert request("/jobs", dispatch)["id"] == job["id"]
        round_record["jobId"] = job["id"]
        save()
        job = wait("/jobs/" + job["id"], {"QUEUED", "DISPATCHING", "RUNNING", "VERIFYING", "PROJECTING"}, 1000)
        round_record["job"] = job
        save()
        assert job["status"] == "READY_FOR_REVIEW", job.get("message")
        assert job["testData"] is True and job["productionAuthorized"] is False
        candidate = job["candidate"]
        assert candidate["verification"]["humanAcceptance"] == "NOT PERFORMED"
        assert candidate["verification"]["technicalStatus"] == "PASS"
        assert proposal["planningEvidence"]["sessionId"] != job["sessionId"]
        assert job["gmSpecificationConfirmation"]["status"] == "BLOCKED"
        assert all(item["status"] == "NOT_TESTED" for item in candidate["verification"]["userAcceptance"])
        published = request("/jobs/" + job["id"] + "/decision", {
            "decision": "accept", "candidateCommit": candidate["candidateCommit"],
            "expectedPublicationRevision": proposal["publicationRevision"]})
        round_record["snapshot"] = published["snapshot"]
        save()
        return published["snapshot"]

    try:
        token = request("/session")["token"]
        first = produce({"text": CONCEPTS[0]}, "jump MVP")
        player = next(obj for obj in first["document"]["objects"] if obj["id"] == "player")
        speed = next(field for field in player["fields"] if field["id"] == "speed")
        new_speed = 300
        assert speed["value"] != new_speed
        feedback = {"objectId": "player", "message": "Keep the existing platforms and controls; make the player cyan so it is easier to track.", "category": "visual"}
        change = {"baseRevision": first["publicationRevision"], "sourceCommit": first["sourceCommit"],
                  "targetObjectIds": ["player"], "fields": [{"objectId": "player", "fieldId": "speed", "value": new_speed}],
                  "feedback": [feedback]}
        second = produce({"text": "", "projectId": first["projectId"],
                          "expectedPublicationRevision": first["publicationRevision"], "changeRequest": change}, "targeted player iteration")
        updated = next(obj for obj in second["document"]["objects"] if obj["id"] == "player")
        assert next(field for field in updated["fields"] if field["id"] == "speed")["value"] == new_speed
        assert second["publicationRevision"] == first["publicationRevision"] + 1
        assert second["sourceCommit"] != first["sourceCommit"]
        puzzle = produce({"text": CONCEPTS[1]}, "puzzle MVP")
        assert puzzle["projectId"] != first["projectId"]
        record.update(status="PASS", finishedAt=now())
        print("GENERAL OBJECT WORKFLOW PROBE PASS (isolated test data; no human acceptance)", flush=True)
    except BaseException as exc:
        record.update(error=str(exc), finishedAt=now())
        raise
    finally:
        save()
        server.shutdown()
        server.server_close()
        coordinator.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--state-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    run(args.state_root.resolve(), args.output.resolve())
