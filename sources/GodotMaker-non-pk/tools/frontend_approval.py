"""Validate a server-issued frontend approval against its durable record.

The caller must authenticate the operator and supply the current server-owned
project context. The client request is intentionally only an event id; a JSON
object supplied by the client is never sufficient evidence of approval.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Mapping, Protocol


PHASE_ACTIONS = {
    "specification": {"approve", "changes_requested", "defer"},
    "run_acceptance": {"accept", "fix", "changes_requested", "defer"},
    "resolve_feedback": {"resolve", "reopen", "defer"},
    "initialize": {"initialize", "defer"},
}
RECORD_FIELDS = frozenset({
    "schemaVersion", "eventId", "operatorId", "projectId", "phase",
    "proposalId", "packetId", "jobId", "candidateId", "revision",
    "gitSpecRef", "runId", "action", "createdAt", "provenance",
    "testData", "productionAuthorized",
})
EXPECTED_PROVENANCE = {
    "kind": "interactive_frontend",
    "input": "frontend",
    "recordedBy": "approval_service",
}


class ApprovalError(ValueError):
    """Approval is absent, stale, malformed, replayed, or out of scope."""


@dataclass(frozen=True)
class ApprovalContext:
    operator_id: str
    project_id: str
    phase: str
    proposal_id: str | None = None
    packet_id: str | None = None
    job_id: str | None = None
    candidate_id: str | None = None
    revision: str | None = None
    git_spec_ref: str | None = None
    run_id: str | None = None
    test_data: bool = False
    production_authorized: bool = True

    def __post_init__(self) -> None:
        if self.phase not in PHASE_ACTIONS:
            raise ApprovalError("unsupported approval phase")
        for name in ("operator_id", "project_id"):
            if not isinstance(getattr(self, name), str) or not getattr(self, name).strip():
                raise ApprovalError(f"missing server-owned {name}")
        if type(self.test_data) is not bool or type(self.production_authorized) is not bool:
            raise ApprovalError("approval authorization flags must be booleans")
        if self.test_data or not self.production_authorized:
            raise ApprovalError("test data or unauthorized context cannot approve production work")


class ApprovalStore(Protocol):
    def get(self, event_id: str) -> Mapping[str, object] | None: ...
    def consume_once(self, event_id: str) -> bool: ...


def _nonempty(record: Mapping[str, object], key: str) -> str:
    value = record.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ApprovalError(f"approval record has invalid {key}")
    return value


def _timestamp(value: object) -> None:
    if not isinstance(value, str):
        raise ApprovalError("approval record has invalid createdAt")
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ApprovalError("approval record has invalid createdAt") from exc
    if parsed.tzinfo is None:
        raise ApprovalError("approval createdAt must include a timezone")


def validate_durable_approval_record(
    event_id: str,
    record: Mapping[str, object],
    context: ApprovalContext,
) -> dict[str, object]:
    """Validate a stored record and project it to trusted stage provenance."""
    if not isinstance(record, Mapping) or set(record) != RECORD_FIELDS:
        raise ApprovalError("durable approval record has an invalid schema")
    if type(record["schemaVersion"]) is not int or record["schemaVersion"] != 1 or record["eventId"] != event_id:
        raise ApprovalError("durable approval record identity is invalid")
    if type(record["testData"]) is not bool or type(record["productionAuthorized"]) is not bool:
        raise ApprovalError("durable approval authorization flags must be booleans")
    if record["testData"] != context.test_data or record["productionAuthorized"] != context.production_authorized:
        raise ApprovalError("durable approval authorization flags do not match server-owned context")
    if not isinstance(record["provenance"], Mapping) or dict(record["provenance"]) != EXPECTED_PROVENANCE:
        raise ApprovalError("approval provenance was not generated by the approval service")
    _timestamp(record["createdAt"])

    bindings = {
        "operatorId": context.operator_id,
        "projectId": context.project_id,
        "phase": context.phase,
        "proposalId": context.proposal_id,
        "packetId": context.packet_id,
        "jobId": context.job_id,
        "candidateId": context.candidate_id,
        "revision": context.revision,
        "gitSpecRef": context.git_spec_ref,
        "runId": context.run_id,
    }
    for key, expected in bindings.items():
        if record.get(key) != expected:
            raise ApprovalError(f"stale or mismatched approval binding: {key}")
    action = _nonempty(record, "action")
    if action not in PHASE_ACTIONS[context.phase]:
        raise ApprovalError("action is invalid for approval phase")
    return {
        "event_id": event_id,
        "operator_id": context.operator_id,
        "phase": context.phase,
        "action": action,
        "provenance": {
            "kind": "interactive_frontend",
            "input": "frontend",
            "recorded_by": "approval_service",
            "event_id": event_id,
            "operator_id": context.operator_id,
            "phase": context.phase,
            "production_authorized": context.production_authorized,
            "test_data": context.test_data,
        },
    }


def consume_frontend_approval(
    client_request: Mapping[str, object],
    context: ApprovalContext,
    store: ApprovalStore,
) -> dict[str, object]:
    """Consume one durable event and return trusted stage-event provenance.

    ``store.consume_once`` must be atomic with respect to concurrent consumers.
    The record is reloaded from that durable store; no approval fields from the
    request are copied into the result.
    """
    if not isinstance(client_request, Mapping) or set(client_request) != {"eventId"}:
        raise ApprovalError("client request must contain only eventId")
    event_id = _nonempty(client_request, "eventId")
    record = store.get(event_id)
    if record is None:
        raise ApprovalError("no durable frontend approval matches eventId")
    result = validate_durable_approval_record(event_id, record, context)
    if not store.consume_once(event_id):
        raise ApprovalError("approval event was already consumed")
    return result
